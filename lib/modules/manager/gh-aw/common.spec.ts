import { isCompiledWorkflow } from './common.ts';

describe('modules/manager/gh-aw/common', () => {
  describe('isCompiledWorkflow()', () => {
    it.each`
      packageFile                                   | content                                                  | expected
      ${'.github/workflows/triage.lock.yml'}        | ${'# gh-aw-metadata: {}\njobs: {}'}                      | ${true}
      ${'.github/workflows/triage.lock.yml'}        | ${'# This file was automatically generated by gh-aw.\n'} | ${true}
      ${'.github/workflows/triage.lock.yml'}        | ${'jobs: {}'}                                            | ${false}
      ${'.github/workflows/triage.yml'}             | ${'# gh-aw-metadata: {}'}                                | ${false}
      ${'.github/workflows/nested/triage.lock.yml'} | ${'# gh-aw-metadata: {}'}                                | ${false}
    `(
      'is $expected for $packageFile',
      ({
        packageFile,
        content,
        expected,
      }: {
        packageFile: string;
        content: string;
        expected: boolean;
      }) => {
        expect(isCompiledWorkflow(packageFile, content)).toBe(expected);
      },
    );
  });
});
