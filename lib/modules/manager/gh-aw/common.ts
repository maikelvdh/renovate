import { regEx } from '../../../util/regex.ts';

/** The pin cache which `gh aw compile` compiles the workflows against. */
export const actionsLockFileName = '.github/aw/actions-lock.json';

/** Matches the workflows which `gh aw compile` generates from their `.md` source. */
export const compiledWorkflowFileRe = regEx(
  /^\.github\/workflows\/[^/]+\.lock\.yml$/,
);

/** Matches the header `gh aw compile` writes at the top of a compiled workflow. */
const compiledWorkflowHeaderRe = regEx(
  /^# (?:gh-aw-metadata:|This file was automatically generated by gh-aw\b)/m,
);

/**
 * Whether a workflow was generated by `gh aw compile`, so that any change to it is undone by the next compile.
 *
 * Its pins are updated through `actions-lock.json` and the `.md` source instead.
 */
export function isCompiledWorkflow(
  packageFile: string,
  content: string,
): boolean {
  return (
    compiledWorkflowFileRe.test(packageFile) &&
    compiledWorkflowHeaderRe.test(content)
  );
}

/** Matches the `.md` sources of the agentic workflows, including the shared imports below `.github/workflows/`. */
export const workflowSourceFileRe = regEx(/^\.github\/workflows\/.+\.md$/);

/**
 * Matches the actions which are released in lock-step with the `gh aw` CLI, i.e. `github/gh-aw/actions/setup` or `github/gh-aw-actions/setup`.
 *
 * `gh aw compile` never pins these beyond the version of the CLI which runs it.
 */
export const ghAwNativeActionRe = regEx(/^github\/gh-aw(?:-actions)?\//);

/** Matches the setup action, whose version is the version of the `gh aw` CLI which compiled the workflows. */
export const ghAwSetupActionRe = regEx(
  /^github\/gh-aw(?:\/actions|-actions)\/setup$/,
);

/**
 * Matches the images which the compiler injects at a tag of its own choosing, such as the firewall and MCP gateway.
 *
 * Their tags move with the CLI, so they are refreshed by a CLI upgrade or lock file maintenance instead.
 */
export const ghAwNativeImageRe = regEx(
  /^ghcr\.io\/github\/(?:gh-aw-[^/:@]+|github-mcp-server)(?:\/|:|@|$)/,
);

/** The `depType` of the setup action, which stands in for the `gh aw` CLI itself. */
export const cliDepType = 'gh-aw';
